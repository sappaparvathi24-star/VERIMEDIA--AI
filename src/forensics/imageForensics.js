/**
 * Computes deep pixel, channel, and entropy statistics using Sharp.
 */
export async function computeImageStatistics(imageBuffer) {
  if (!imageBuffer || !Buffer.isBuffer(imageBuffer)) {
    return null;
  }
  try {
    const img = sharp(imageBuffer);
    const meta = await img.metadata();
    const stats = await img.stats();

    // Compute luminance metrics
    const channels = stats.channels.map((c, idx) => ({
      index: idx,
      name: idx === 0 ? 'R' : idx === 1 ? 'G' : idx === 2 ? 'B' : 'A',
      min: c.min,
      max: c.max,
      mean: Number(c.mean.toFixed(2)),
      stdev: Number(c.stdev.toFixed(2)),
      contrastIndex: Number((Math.log2(c.stdev + 1) * 1.4).toFixed(2))
    }));

    const isGrayscale = stats.isOpaque && channels.length >= 3 &&
      Math.abs(channels[0].mean - channels[1].mean) < 2 &&
      Math.abs(channels[1].mean - channels[2].mean) < 2;

    const meanLuminance = channels.length >= 3
      ? Number((0.299 * channels[0].mean + 0.587 * channels[1].mean + 0.114 * channels[2].mean).toFixed(2))
      : (channels[0]?.mean || 0);

    const meanVariance = channels.length >= 3
      ? Number(((channels[0].stdev + channels[1].stdev + channels[2].stdev) / 3).toFixed(2))
      : (channels[0]?.stdev || 0);

    return {
      format: meta.format || 'unknown',
      width: meta.width || 0,
      height: meta.height || 0,
      space: meta.space || 'srgb',
      channels: meta.channels || 3,
      depth: meta.depth || 'uchar',
      density: meta.density || 72,
      hasAlpha: Boolean(meta.hasAlpha),
      isOpaque: Boolean(stats.isOpaque),
      isGrayscale,
      meanLuminance,
      meanVariance,
      channelStats: channels,
      dominant: stats.dominant || null,
      entropy: stats.entropy ? Number(stats.entropy.toFixed(2)) : Number((meanVariance / 10).toFixed(2))
    };
  } catch (err) {
    if (!err.message || !err.message.includes('unsupported image format')) {
      console.warn('[SharpStats] Failed to compute image statistics:', err.message);
    }
    return null;
  }
}

